#!/usr/bin/env node

import { createHash } from 'node:crypto'
import { writeFileSync } from 'node:fs'
import { parse } from 'yaml'

// Deliberately pinned. Updating this is a reviewed source change, never a
// runtime network operation.
const commit = 'd51285770b3093e575bdf8d0bd81786fe1efbd6d'
const source = 'https://github.com/nostr-protocol/registry-of-kinds'
const schemaUrl = `https://raw.githubusercontent.com/nostr-protocol/registry-of-kinds/${commit}/schema.yaml`

const response = await fetch(schemaUrl)
if (!response.ok) {
  throw new Error(`Failed to fetch pinned Registry of Kinds: HTTP ${response.status}`)
}

const yaml = await response.text()
const schema = parse(yaml, { maxAliasCount: 10_000 })
if (!schema || typeof schema !== 'object' || !schema.kinds || !schema.generic_tags) {
  throw new Error('Pinned Registry of Kinds has an unexpected shape')
}

const sha256 = createHash('sha256').update(yaml, 'utf8').digest('hex')
const snapshot = {
  generic_tags: schema.generic_tags,
  kinds: schema.kinds,
}
const output = `// Generated by scripts/update-kind-registry.mjs. Do not edit by hand.\n` +
  `// Source: ${source}/commit/${commit}\n\n` +
  `import type { KindRegistrySchema } from './registry-types.js'\n\n` +
  `export const KIND_REGISTRY_SOURCE = ${JSON.stringify(source)}\n` +
  `export const KIND_REGISTRY_COMMIT = ${JSON.stringify(commit)}\n` +
  `export const KIND_REGISTRY_SHA256 = ${JSON.stringify(sha256)}\n` +
  `export const PINNED_KIND_REGISTRY: KindRegistrySchema = ${JSON.stringify(snapshot, null, 2)}\n`

writeFileSync(new URL('../src/event-validation/registry.generated.ts', import.meta.url), output)
console.error(`Pinned ${Object.keys(schema.kinds).length} event kinds at ${commit} (${sha256})`)
